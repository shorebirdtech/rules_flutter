// Derives the `libraries.json` that names the dart: libraries Flutter provides.
//
// The engine builds its own libraries spec but does not publish it, and the
// bundled Dart SDK's spec has no `flutter` target. Flutter's set is the VM's
// common set, less `dart:mirrors` (which the engine refuses to load, even when
// nothing reaches the importing library) and plus `dart:ui`.
//
// Only the library names are meaningful. A consumer reads which dart:
// libraries a Flutter program may import, to leave out of a compile any
// library that needs one Flutter lacks. Compiles resolve dart: libraries from
// the platform dill and never read this file.
//
// Usage: libraries_spec.dart --sdk-libraries=<libraries.json> --output=<file>
//
// Both paths are relative to the same directory, which is how the SDK's own
// paths are rebased onto the output's location.

import 'dart:convert';
import 'dart:io';

const _droppedLibraries = ['mirrors'];

Object? _rebase(Object? value, String prefix) {
  if (value is String) return prefix + value;
  if (value is List) return [for (final v in value) prefix + (v as String)];
  return value;
}

/// Derives the Flutter libraries spec from the Dart SDK's.
///
/// [sdkLibDir] is the SDK's `lib/` directory relative to the written file,
/// with a trailing slash; the SDK's paths are relative to it.
Map<String, Object?> flutterLibrariesSpec(
  Map<String, Object?> sdkSpec,
  String sdkLibDir,
) {
  final common = (sdkSpec['vm_common'] as Map)['libraries'] as Map;
  final libraries = <String, Object?>{};
  for (final entry in common.entries) {
    if (_droppedLibraries.contains(entry.key)) continue;
    final library = Map<String, Object?>.from(entry.value as Map);
    library['uri'] = sdkLibDir + (library['uri'] as String);
    if (library.containsKey('patches')) {
      library['patches'] = _rebase(library['patches'], sdkLibDir);
    }
    libraries[entry.key as String] = library;
  }
  // dart:ui's source ships in the separate sky_engine artifact; nothing here
  // resolves the URI.
  libraries['ui'] = {'uri': '../sky_engine/lib/ui/ui.dart'};
  return {
    'comment:0':
        'Generated by rules_flutter from the Dart SDK\'s libraries.json. '
        'Names the dart: libraries a Flutter program can import; not for '
        'compiling.',
    'flutter': {'libraries': libraries},
  };
}

/// [target] as seen from the directory of [from]; both are relative to one
/// root.
String relativeDirectory(String from, String target) {
  final depth = from.split('/').length - 1;
  return '${'../' * depth}$target';
}

void main(List<String> args) {
  String? sdkLibraries;
  String? output;
  for (final arg in args) {
    if (arg.startsWith('--sdk-libraries=')) {
      sdkLibraries = arg.substring('--sdk-libraries='.length);
    } else if (arg.startsWith('--output=')) {
      output = arg.substring('--output='.length);
    } else {
      stderr.writeln('libraries_spec: unknown argument $arg');
      exit(2);
    }
  }
  if (sdkLibraries == null || output == null) {
    stderr.writeln(
      'usage: libraries_spec --sdk-libraries=<path> --output=<path>',
    );
    exit(2);
  }
  final sdkSpec = json.decode(
    File(sdkLibraries).readAsStringSync(),
  ) as Map<String, Object?>;
  final libDir = sdkLibraries.substring(0, sdkLibraries.lastIndexOf('/') + 1);
  final spec = flutterLibrariesSpec(sdkSpec, relativeDirectory(output, libDir));
  File(output).writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(spec)}\n',
  );
}
